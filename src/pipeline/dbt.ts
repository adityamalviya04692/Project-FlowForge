import { ancestors, inputsOf, slug, stepNames, topoOrder } from './graph';
import { nodeSelect } from './sql';
import type { PNode, Pipeline } from './types';

export interface GeneratedFile {
  path: string;
  content: string;
}

const yamlStr = (s: string) => (/^[\w./-]+$/.test(s) ? s : JSON.stringify(s));

/** A small dbt project: one source block, one model per Output, tests from Quality nodes. */
export function toDbt(p: Pipeline, columns: Map<string, string[]>): GeneratedFile[] {
  const project = slug(p.name) || 'flowforge_project';
  const names = stepNames(p);
  const { order } = topoOrder(p);
  const sources = order.filter((n): n is Extract<PNode, { kind: 'source' }> => n.kind === 'source');
  const outputs = order.filter((n): n is Extract<PNode, { kind: 'output' }> => n.kind === 'output');

  const bySchema = new Map<string, Set<string>>();
  for (const s of sources) {
    const [schema, table] = s.config.table.includes('.') ? s.config.table.split('.') : ['raw', s.config.table];
    if (!bySchema.has(schema)) bySchema.set(schema, new Set());
    bySchema.get(schema)!.add(table);
  }
  const sourcesYml = [
    'version: 2',
    '',
    'sources:',
    ...[...bySchema].flatMap(([schema, tables]) => [`  - name: ${yamlStr(schema)}`, `    schema: ${yamlStr(schema)}`, '    tables:', ...[...tables].map((t) => `      - name: ${yamlStr(t)}`)]),
  ].join('\n');

  const files: GeneratedFile[] = [
    {
      path: 'dbt_project.yml',
      content: [`name: ${project}`, "version: '1.0.0'", 'config-version: 2', `profile: ${project}`, '', "model-paths: ['models']", '', 'models:', `  ${project}:`, '    +materialized: table'].join('\n'),
    },
    { path: 'models/sources.yml', content: sourcesYml },
  ];

  const tests: string[] = [];
  let needsUtils = false;
  for (const o of outputs) {
    const deps = ancestors(p, o.id);
    const steps = order.filter((n) => deps.has(n.id));
    const ctes = steps.map((n) => {
      const ins = inputsOf(p, n.id).map((i) => ({ ref: names.get(i.id)!, cols: columns.get(i.id) ?? [] }));
      let ref = '';
      if (n.kind === 'source') {
        const [schema, table] = n.config.table.includes('.') ? n.config.table.split('.') : ['raw', n.config.table];
        ref = `{{ source('${schema}', '${table}') }}`;
      }
      return `${names.get(n.id)} as (\n    ${nodeSelect(n, ins, 'spark', ref).replace(/\n/g, '\n    ')}\n)`;
    });
    const model = slug(o.config.table.split('.').pop() ?? o.label);
    const schema = o.config.table.includes('.') ? o.config.table.split('.')[0] : undefined;
    const config = [`materialized='${o.config.mode === 'append' ? 'incremental' : 'table'}'`, `file_format='${o.config.format}'`, ...(schema ? [`schema='${schema}'`] : [])];
    const last = names.get(inputsOf(p, o.id)[0]?.id ?? '') ?? 'missing_input';
    files.push({ path: `models/marts/${model}.sql`, content: `{{ config(${config.join(', ')}) }}\n\n-- ${o.label}: generated by FlowForge\nwith ${ctes.join(',\n\n')}\n\nselect * from ${last}\n` });

    // Quality nodes upstream of this output become dbt tests on the model.
    const colTests = new Map<string, string[]>();
    for (const q of steps.filter((n): n is Extract<PNode, { kind: 'quality' }> => n.kind === 'quality')) {
      for (const c of q.config.checks.filter((x) => x.column && (columns.get(o.id) ?? []).includes(x.column))) {
        const list = colTests.get(c.column) ?? [];
        if (c.rule === 'not_null' || c.rule === 'unique') list.push(`          - ${c.rule}`);
        if (c.rule === 'accepted_values') list.push('          - accepted_values:', `              values: [${c.arg1.split(',').map((v) => JSON.stringify(v.trim())).join(', ')}]`);
        if (c.rule === 'between') {
          needsUtils = true;
          list.push('          - dbt_utils.accepted_range:', ...(c.arg1.trim() ? [`              min_value: ${c.arg1.trim()}`] : []), ...(c.arg2.trim() ? [`              max_value: ${c.arg2.trim()}`] : []));
        }
        if (c.rule === 'matches') list.push(`          # regex check (${c.arg1}): add dbt_expectations.expect_column_values_to_match_regex`);
        colTests.set(c.column, list);
      }
    }
    tests.push(`  - name: ${model}`, `    description: ${JSON.stringify(`${o.label} (${o.config.table})`)}`, '    columns:', ...(columns.get(o.id) ?? []).map((c) => [`      - name: ${yamlStr(c)}`, ...(colTests.has(c) ? ['        tests:', ...colTests.get(c)!] : [])].join('\n')));
  }
  files.push({ path: 'models/marts/schema.yml', content: ['version: 2', '', 'models:', ...tests].join('\n') });
  if (needsUtils) files.push({ path: 'packages.yml', content: 'packages:\n  - package: dbt-labs/dbt_utils\n    version: [">=1.1.0", "<2.0.0"]' });
  files.push({ path: 'README.md', content: `# ${p.name}\n\nGenerated by FlowForge. Run with:\n\n\`\`\`bash\n${needsUtils ? 'dbt deps\n' : ''}dbt build --select marts\n\`\`\`\n` });
  return files;
}
